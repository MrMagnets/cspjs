-- psql "$DATABASE_URL" -f backend/sql/migrations/2026_11_community.sql

BEGIN;

-- ---------------------------------------------------------------------------
-- users：小猴值、信用分、封禁、称号、出题权限
-- ---------------------------------------------------------------------------
ALTER TABLE users ADD COLUMN IF NOT EXISTS monkey_score integer NOT NULL DEFAULT 0;
ALTER TABLE users ADD COLUMN IF NOT EXISTS credit_score integer NOT NULL DEFAULT 100;
ALTER TABLE users ADD COLUMN IF NOT EXISTS status varchar(16) NOT NULL DEFAULT 'normal';
ALTER TABLE users ADD COLUMN IF NOT EXISTS ban_until timestamptz NULL;
ALTER TABLE users ADD COLUMN IF NOT EXISTS title varchar(64) NOT NULL DEFAULT '';
ALTER TABLE users ADD COLUMN IF NOT EXISTS can_create_problem boolean NOT NULL DEFAULT true;

-- ---------------------------------------------------------------------------
-- problems：P/T/S 题库隔离 + 唯一题号
-- ---------------------------------------------------------------------------
ALTER TABLE problems ADD COLUMN IF NOT EXISTS pool_type varchar(8) NOT NULL DEFAULT 'P';
ALTER TABLE problems ADD COLUMN IF NOT EXISTS problem_number varchar(32) NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_problems_problem_number
    ON problems (problem_number) WHERE problem_number IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_problems_pool_status ON problems (pool_type, status);

-- ---------------------------------------------------------------------------
-- contests / contest_problems / contest_results / cheat_logs
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS contests (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(200) NOT NULL,
    description text NOT NULL DEFAULT '',
    contest_type varchar(16) NOT NULL DEFAULT 'official',
    status varchar(16) NOT NULL DEFAULT 'upcoming',
    start_at timestamptz NOT NULL,
    end_at timestamptz NOT NULL,
    duration_minutes integer NOT NULL DEFAULT 120,
    created_by integer NULL REFERENCES users(id) ON DELETE SET NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS contest_problems (
    contest_id integer NOT NULL REFERENCES contests(id) ON DELETE CASCADE,
    problem_id integer NOT NULL REFERENCES problems(id) ON DELETE CASCADE,
    order_no integer NOT NULL DEFAULT 1,
    score integer NOT NULL DEFAULT 10,
    PRIMARY KEY (contest_id, problem_id)
);

CREATE TABLE IF NOT EXISTS contest_results (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contest_id integer NOT NULL REFERENCES contests(id) ON DELETE CASCADE,
    user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    score integer NOT NULL DEFAULT 0,
    cheat_count integer NOT NULL DEFAULT 0,
    status varchar(16) NOT NULL DEFAULT 'ongoing',
    submitted_at timestamptz NULL,
    CONSTRAINT uq_contest_result_user UNIQUE (contest_id, user_id)
);
CREATE INDEX IF NOT EXISTS ix_contest_results_contest ON contest_results (contest_id);
CREATE INDEX IF NOT EXISTS ix_contest_results_user ON contest_results (user_id);

CREATE TABLE IF NOT EXISTS cheat_logs (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contest_id integer NOT NULL REFERENCES contests(id) ON DELETE CASCADE,
    user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    event varchar(32) NOT NULL DEFAULT 'visibilitychange',
    detail text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_cheat_logs_contest ON cheat_logs (contest_id);
CREATE INDEX IF NOT EXISTS ix_cheat_logs_user ON cheat_logs (user_id);

-- ---------------------------------------------------------------------------
-- submissions：答题耗时 + 比赛来源
-- ---------------------------------------------------------------------------
ALTER TABLE submissions ADD COLUMN IF NOT EXISTS time_spent integer NOT NULL DEFAULT 0;
ALTER TABLE submissions ADD COLUMN IF NOT EXISTS contest_id integer NULL
    REFERENCES contests(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS ix_submissions_contest ON submissions (contest_id);

-- ---------------------------------------------------------------------------
-- discussions / comments / reports
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS discussions (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(200) NOT NULL,
    content_md text NOT NULL DEFAULT '',
    category varchar(16) NOT NULL DEFAULT '学术',
    author_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    problem_id integer NULL REFERENCES problems(id) ON DELETE SET NULL,
    is_pinned boolean NOT NULL DEFAULT false,
    is_locked boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_discussions_author ON discussions (author_id);

CREATE TABLE IF NOT EXISTS comments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    discussion_id integer NOT NULL REFERENCES discussions(id) ON DELETE CASCADE,
    author_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    content_md text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_comments_discussion ON comments (discussion_id);
CREATE INDEX IF NOT EXISTS ix_comments_author ON comments (author_id);

CREATE TABLE IF NOT EXISTS reports (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    target_type varchar(16) NOT NULL,
    target_id integer NOT NULL,
    reason text NOT NULL DEFAULT '',
    status varchar(16) NOT NULL DEFAULT 'pending',
    created_at timestamptz NOT NULL DEFAULT now(),
    resolved_by integer NULL REFERENCES users(id) ON DELETE SET NULL,
    resolved_at timestamptz NULL
);

-- ---------------------------------------------------------------------------
-- appeals
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS appeals (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    contest_id integer NULL REFERENCES contests(id) ON DELETE SET NULL,
    reason text NOT NULL DEFAULT '',
    video_url varchar(512) NOT NULL DEFAULT '',
    status varchar(16) NOT NULL DEFAULT 'pending',
    admin_id integer NULL REFERENCES users(id) ON DELETE SET NULL,
    admin_note text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now(),
    reviewed_at timestamptz NULL
);
CREATE INDEX IF NOT EXISTS ix_appeals_user ON appeals (user_id);

COMMIT;
